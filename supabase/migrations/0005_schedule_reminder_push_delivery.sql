--   2. KeepDearly is deployed on Vercel, and Vercel Cron Jobs are enabled for
--      the project. The scheduler is now Vercel, not the database:
--        Vercel Cron  ->  GET /api/reminders/due  ->  CRON_SECRET bearer check
--      Vercel holds CRON_SECRET as a project environment variable and sends it
--      as `Authorization: Bearer <CRON_SECRET>`. The schedule lives in
--      `vercel.json` at the repository root.
--
-- Nothing here was ever applied to any database, and no Vault secret was ever
-- created, so there is no schema to roll back and no `0005` row in any
-- migration history. No replacement migration was written, because the
-- scheduler now lives entirely outside the database; migration 0004 (the
-- atomic `claim_due_reminder`) is untouched and remains the only
-- delivery-related database change.
--
-- This file is kept in place, as an inert tombstone: every statement has been
-- removed, so even if a future `supabase db push` reads it, it cannot install
-- the unavailable extension or create the obsolete scheduler. Delete it freely
-- if you prefer — the number is not referenced by any later migration.
--
-- The abandoned design, for the record: a `security definer` wrapper
-- (`public.keepdearly_run_reminder_delivery()`) read `keepdearly_delivery_url`
-- and `keepdearly_cron_secret` from `vault.decrypted_secrets` at execution time
-- and POSTed with `net.http_post`, scheduled by `cron.schedule(...)` on
-- '* * * * *'. The one good property of that design — that the stored cron
-- command contained no secret — is now preserved for a stronger reason: there
-- is no database-side scheduler at all, and CRON_SECRET never enters the
-- database.
-- =============================================================================


-- KeepDearly -- Phase 6D: Plus purchases and authoritative entitlement activation.
--
-- Run this AFTER 0010_scheduled_message_cancel_rpc.sql. Migrations 0001-0010 are
-- already applied and are left exactly as they are.
--
-- What this migration does
-- -----------------------
-- - plus_purchases: one row per KeepDearly-initiated payment attempt.
-- - complete_plus_purchase(): the ONLY way profiles.plus_active turns true.
-- - fail_plus_purchase(): records a terminal failure. Never grants Plus.
--
-- What it deliberately does NOT do
-- -------------------------------
-- - no payment provider code, HTTP route, cron, or UI.
-- - no change to profiles.plus_active privileges. The 0007 protection
--   (table-level UPDATE revoked, only full_name/avatar_url re-granted) is left
--   intact -- this file only ADDS a service-role path that can set the flag.
-- - no change to scheduled_messages or anything in Phase 6C.
--
-- The invariant
-- ------------
--   Plus is granted only by complete_plus_purchase, and only for a row that
--   already exists with provider = nylonpay, amount = 2000 and currency = UGX.
--   All three are CHECK constraints on the table, so the decision is made in
--   the database and cannot be steered by a request body, a webhook payload,
--   or a compromised caller.

-- ---------------------------------------------------------------------------
-- 1. plus_purchases
-- ---------------------------------------------------------------------------
-- One row per payment attempt that KEEPEARLY started. The reference is
-- generated by the server before the provider is called, so a transaction can
-- always be reconciled back to the user who asked for it.
create table if not exists public.plus_purchases (
  id uuid primary key default gen_random_uuid(),

  -- The buyer. Always the authenticated session user id on the server, never a
  -- value taken from a request body or a webhook payload.
  user_id uuid not null references auth.users (id) on delete cascade,

  -- The only provider this build supports. A CHECK rather than free text so a
  -- second provider cannot be smuggled in by a bad write.
  provider text not null default 'nylonpay',

  -- The UUID KeepDearly generated and passed to the provider as reference.
  -- This is the join key between a provider transaction and a KeepDearly user,
  -- and it is what makes activation idempotent.
  provider_reference uuid not null,

  -- The provider own transaction id, recorded once the outcome is known. Null
  -- while pending; useful for reconciliation with the Nylon Pay dashboard.
  provider_transaction_id text,

  -- What the server charged. Both are constrained, not merely defaulted, so no
  -- code path can create a Plus purchase at any other price.
  amount integer not null,
  currency text not null,

  -- pending -> completed | failed. One payment attempt, one terminal state.
  status text not null default 'pending',

  -- The Mobile Money number prompted, kept so a failed payment can be reconciled
  -- with the customer telco receipt. Never logged by the app.
  payer_phone text,

  -- A short, non-sensitive category ONLY (for example insufficient_balance).
  -- Provider error text can echo the payer number, so it is never stored here.
  failure_reason text,

  -- Set once, when the purchase completes. Null while pending or failed.
  completed_at timestamptz,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint plus_purchases_status_check
    check (status in ('pending', 'completed', 'failed')),

  constraint plus_purchases_currency_check
    check (currency = 'UGX'),

  -- The Plus price is UGX 2,000 and nothing else. Enforced here so the decision
  -- to grant Plus can never rest on a caller-supplied number.
  constraint plus_purchases_amount_check
    check (amount = 2000),

  constraint plus_purchases_provider_check
    check (provider = 'nylonpay'),

  -- One row per provider reference. This is the backbone of idempotency: a
  -- replayed webhook resolves to the same row instead of creating a second one.
  constraint plus_purchases_provider_reference_key
    unique (provider_reference),

  -- A user cannot have two live attempts at once. This is what stops a
  -- double-tap on the Pay button from charging twice: the second attempt fails
  -- the unique check and the server returns the first reference instead. A
  -- terminal row (completed/failed) no longer occupies the slot, so paying again
  -- after a failure works normally.
  constraint plus_purchases_one_pending_per_user_key
    unique (user_id) where status = 'pending'
);
comment on table public.plus_purchases is
  'One KeepDearly-initiated Nylon Pay payment attempt for Plus (UGX 2,000, one time). Written server-side only; the client may read its own rows for status history but can never insert, update or delete them.';

comment on column public.plus_purchases.provider_reference is
  'UUID generated by KeepDearly and passed to Nylon Pay as the transaction reference. Unique, and the key used to reconcile a provider transaction with this purchase.';

comment on column public.plus_purchases.payer_phone is
  'Mobile Money number prompted for this payment, kept for reconciliation with a telco receipt. Never logged by the app and never sent to the browser.';

comment on column public.plus_purchases.failure_reason is
  'Short failure category only, e.g. insufficient_balance. Raw provider error text is never stored because it can echo the payer phone number.';

-- The usual shared updated_at trigger from Phase 1, exactly as scheduled_messages
-- uses it in 0007.
drop trigger if exists plus_purchases_set_updated_at on public.plus_purchases;
create trigger plus_purchases_set_updated_at
  before update on public.plus_purchases
  for each row execute function public.set_updated_at();

-- Reconciliation looks rows up by reference (already unique-indexed above) and an
-- operator looks for interrupted attempts by user. The second index is partial so
-- it stays tiny as completed purchases accumulate.
create index if not exists plus_purchases_pending_idx
  on public.plus_purchases (user_id)
  where status = 'pending';

-- ---------------------------------------------------------------------------
-- 2. RLS and grants
-- ---------------------------------------------------------------------------
-- anon gets nothing at all: a signed-out client cannot read purchase history.
-- authenticated gets SELECT and nothing else -- no INSERT, no UPDATE, no DELETE.
-- There is deliberately no client-writable path into this table; every mutation
-- goes through the two SECURITY DEFINER functions below, which are service-role
-- only. So a signed-in user cannot create a completed purchase, flip a status,
-- change a reference, or point a purchase at another account.
alter table public.plus_purchases enable row level security;

revoke all on table public.plus_purchases from anon;
revoke all on table public.plus_purchases from authenticated;
grant select on table public.plus_purchases to authenticated;

drop policy if exists 'Users can read their own plus purchases' on public.plus_purchases;
create policy 'Users can read their own plus purchases'
  on public.plus_purchases for select
  using (auth.uid() = user_id);
-- ---------------------------------------------------------------------------
-- 3. complete_plus_purchase(uuid, text)
-- ---------------------------------------------------------------------------
-- The single authoritative path to Plus.
--
-- SECURITY DEFINER runs as the table owner, so it bypasses RLS. That is safe
-- only because this function derives the user from the purchase row itself and
-- never from an argument: the only input is the reference, which resolves to
-- exactly one row, whose user_id is whoever started the payment. A caller
-- therefore cannot choose the account that gets Plus.
--
-- Idempotent by construction. The UPDATE only matches while the row is not
-- already completed, so Nylon Pay at-least-once webhook delivery -- and any
-- manual retry -- finds nothing to do, reports out_activated = false, and
-- returns successfully rather than raising. plus_active is written with
-- set plus_active = true, which is itself idempotent.
--
-- The amount/currency CHECK is re-tested here as well. The caller verifies the
-- amount against Nylon Pay before calling, but the entitlement decision belongs
-- in the database, so the database is where it is finally enforced.
create or replace function public.complete_plus_purchase(
  p_reference uuid,
  p_provider_transaction_id text
)
returns table (
  out_user_id uuid,
  out_activated boolean
)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_purchase public.plus_purchases%rowtype;
begin
  if p_reference is null then
    raise exception 'complete_plus_purchase: p_reference is required'
      using errcode = '22004';
  end if;

  select p.* into v_purchase
  from public.plus_purchases as p
  where p.provider_reference = p_reference;

  -- An unknown reference is not worth distinguishing for the caller, and the
  -- message says nothing about which references exist.
  if not found then
    raise exception 'complete_plus_purchase: unknown reference'
      using errcode = 'P0002';
  end if;

  if v_purchase.amount <> 2000 or v_purchase.currency <> 'UGX' then
    raise exception 'complete_plus_purchase: refusing to grant Plus for a purchase that is not 2000 UGX'
      using errcode = '42501';
  end if;

  out_user_id := v_purchase.user_id;

  -- Only fires while the purchase is not already completed. Zero rows here is
  -- the normal, expected result of a duplicate callback.
  update public.plus_purchases as p
  set status = 'completed',
      provider_transaction_id = coalesce(p.provider_transaction_id, p_provider_transaction_id),
      completed_at = coalesce(p.completed_at, now()),
      failure_reason = null,
      updated_at = now()
  where p.id = v_purchase.id
    and p.status <> 'completed'
  returning true into out_activated;

  if out_activated is null then
    out_activated := false;
  end if;

  -- Plus is set only on that transition, and only for the row own user.
  if out_activated then
    update public.profiles as pr
    set plus_active = true
    where pr.id = v_purchase.user_id;
  end if;

  return next;
end;
$$;

comment on function public.complete_plus_purchase(uuid, text) is
  'Records a verified successful Plus payment and sets profiles.plus_active for the purchase own user. Idempotent: a duplicate callback activates nothing and does not error. service_role only.';
-- ---------------------------------------------------------------------------
-- 4. fail_plus_purchase(uuid, text)
-- ---------------------------------------------------------------------------
-- Records a terminal failure. It NEVER touches plus_active, and it only moves a
-- row that is still pending, so a late failure callback can never undo a payment
-- that already succeeded.
create or replace function public.fail_plus_purchase(
  p_reference uuid,
  p_failure_reason text
)
returns table (
  out_user_id uuid,
  out_recorded boolean
)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_purchase public.plus_purchases%rowtype;
begin
  if p_reference is null then
    raise exception 'fail_plus_purchase: p_reference is required'
      using errcode = '22004';
  end if;

  select p.* into v_purchase
  from public.plus_purchases as p
  where p.provider_reference = p_reference;

  if not found then
    raise exception 'fail_plus_purchase: unknown reference'
      using errcode = 'P0002';
  end if;

  out_user_id := v_purchase.user_id;

  update public.plus_purchases as p
  set status = 'failed',
      -- A short category only. Truncated so a verbose provider string can
      -- never fill the column.
      failure_reason = left(coalesce(p_failure_reason, 'payment_failed'), 120),
      updated_at = now()
  where p.id = v_purchase.id
    and p.status = 'pending'
  returning true into out_recorded;

  if out_recorded is null then
    out_recorded := false;
  end if;

  return next;
end;
$$;

comment on function public.fail_plus_purchase(uuid, text) is
  'Records a terminal Plus payment failure as a short category. Never grants Plus and never downgrades a completed purchase. service_role only.';

-- ---------------------------------------------------------------------------
-- 5. Execute privileges
-- ---------------------------------------------------------------------------
-- Default-deny first, exactly as 0008/0009/0010. These two functions are the
-- only writers of purchase rows and the only activators of Plus, so they are
-- granted to service_role alone: no authenticated user and no anonymous caller
-- can invoke them. In particular there is no client-callable activate-Plus
-- function to point at.
revoke all on function public.complete_plus_purchase(uuid, text) from public;
revoke all on function public.complete_plus_purchase(uuid, text) from anon;
revoke all on function public.complete_plus_purchase(uuid, text) from authenticated;
grant execute on function public.complete_plus_purchase(uuid, text) to service_role;

revoke all on function public.fail_plus_purchase(uuid, text) from public;
revoke all on function public.fail_plus_purchase(uuid, text) from anon;
revoke all on function public.fail_plus_purchase(uuid, text) from authenticated;
grant execute on function public.fail_plus_purchase(uuid, text) to service_role;

